from PIL import Image  # импортируем pillow для работы с изображением
import numpy as np  # импортируем numpy для работы с массивами
import matplotlib.pyplot as plt  # импортируем matplotlib для визуализации изображения
from scipy.ndimage import binary_erosion, binary_dilation  # импортируем функции непосредственно для обработки изображения

# Открываем изображение и конвертируем его в формат RGBA (с альфа-каналом)
image = Image.open('4_cats.png').convert("RGBA")
data = np.array(image)  # преобразуем изображение в массив numpy
h, w, _ = data.shape  # находим высоту и ширину изображения

# Разбиваем изображение на 4 сектора, чтобы обрабатывать их по отдельности
sectors = [
    data[:h // 2, :w // 2, :],  # верхний левый сектор
    data[:h // 2, w // 2:, :],  # верхний правый сектор
    data[h // 2:, :w // 2, :],  # нижний левый сектор
    data[h // 2:, w // 2:, :]    # нижний правый сектор
]

def remove_background(sector, lower_bound, upper_bound, exclusion_areas):
    """
    Эта функция удаляет фон из заданного сектора изображения.
    Идея состоит в том, чтобы проводить очистку от фона на основе двух границ значений цвета пикселей,
    которые я нашла путём ювелирной работы. Чтобы улучшить результат и на самих кошках не исчезали пиксели,
    цвет которых совпадает с фоном, я решила примерно выделить прямоугольники в местах, где кошки,
    и сделать эти прямоугольники недосягаемыми областями (т.е. там фон мы не чистим).
    Можно также ещё улучшить решение, и сделать такие же маски для ушей, но задание допускает такие оплошности:)

    :param sector: Сектор изображения, который мы хотим обработать.
    :param lower_bound: Нижняя граница цвета для создания маски.
    :param upper_bound: Верхняя граница цвета для создания маски.
    :param exclusion_areas: Области, которые мы не хотим затрагивать.
    :return: Новый сектор с удаленным фоном.
    """
    # Извлекаем цветовые каналы из сектора.
    red, green, blue = sector[:, :, 0], sector[:, :, 1], sector[:, :, 2]

    # Создаем маску для выделения цветов в заданном диапазоне.
    mask = (
        (red >= lower_bound[0]) & (red <= upper_bound[0]) &
        (green >= lower_bound[1]) & (green <= upper_bound[1]) &
        (blue >= lower_bound[2]) & (blue <= upper_bound[2])
    )

    # Убираем шум из маски сначала с помощью эрозии, затем используем дилатацию для восстановления формы объектов
    mask_cleaned = binary_dilation(binary_erosion(mask, structure=np.ones((5, 5))), structure=np.ones((5, 5)))

    # Создаем маску исключения для областей, которые не нужно обрабатывать
    mask_exclusion = np.zeros(sector.shape[:2], dtype=bool)  # начинаем с пустой маски
    for rect_start, rect_size in exclusion_areas:  # проходим по всей исключающей
        x_start, y_start = rect_start  # получаем начальные координаты области
        rect_width, rect_height = rect_size  # получаем размеры области
        mask_exclusion[y_start:y_start + rect_height, x_start:x_start + rect_width] = True  # обозначаем область как исключенную

    # Создаем новый массив для сектора с альфа-каналом (прозрачностью)
    new_sector = np.zeros((*sector.shape[:2], 4), dtype=np.uint8)

    # Копируем RGB каналы из оригинального сектора в новый массив
    new_sector[..., :3] = sector[..., :3]

    # Создаем альфа-канал и заполняем его значением 255 (полная непрозрачность)
    alpha_channel = np.ones(sector.shape[:2], dtype=np.uint8) * 255

    # Убираем фон, делая прозрачными только те области, которые соответствуют маске и не являются исключениями
    alpha_channel[mask_cleaned & ~mask_exclusion] = 0

    new_sector[..., 3] = alpha_channel  # присваиваем альфа-канал новому сектору

    return new_sector  # возвращаем обработанный сектор

# Определяем области исключения для каждого сектора
exclusion_areas = [
    [((130, 130), (240, 400))],  # верхний левый сектор
    [((150, 130), (230, 400))],  # верхний правый сектор
    [((110, 130), (260, 400))],  # нижний левый сектор
    [((140, 130), (255, 400))]   # нижний правый сектор
]

# Задаем параметры маски для каждого сектора (нижние и верхние границы цвета).
bounds = [
    ([215, 170, 35], [250, 220, 110]),  # верхний левый сектор
    ([120, 110, 0], [235, 190, 65]),    # верхний правый сектор
    ([175, 100, 0], [255, 215, 100]),   # нижний левый сектор
    ([100, 50, 0], [230, 150, 30])      # нижний правый сектор
]

# Обрабатываем каждый сектор и удаляем фон с помощью написанной функции
processed_sectors = [
    remove_background(sectors[i].copy(), bounds[i][0], bounds[i][1], exclusion_areas[i])
    for i in range(4)  # проходим по всем четырем секторам
]

# Создаем новый массив для объединенного изображения с теми же размерами, что и оригинал
processed_image = np.zeros_like(data)

# Вставляем обработанные сектора обратно в общий массив по их позициям.
processed_image[:h // 2, :w // 2] = processed_sectors[0]  # верхний левый сектор
processed_image[:h // 2, w // 2:] = processed_sectors[1]  # верхний правый сектор
processed_image[h // 2:, :w // 2] = processed_sectors[2]  # нижний левый сектор
processed_image[h // 2:, w // 2:] = processed_sectors[3]  # нижний правый сектор

# Преобразуем обработанный массив обратно в изображение PIL и сохраняем
result_image = Image.fromarray(processed_image)
result_image.save('processed_image.png')  # сохраняем изображение
result_image.show()  # отображаем изображение

# Используем matplotlib для отображения оригинального и обработанного изображений рядом друг с другом
plt.figure(figsize=(10, 5))  # устанавливаем размер окна для графиков

plt.subplot(1, 2, 1)  # создаем подграфик для оригинального изображения
plt.title('Оригинальное изображение')  # заголовок для оригинального изображения
plt.imshow(image)  # отображаем оригинальное изображение
plt.axis('off')  # выключаем оси для более чистого вида

plt.subplot(1, 2, 2)  # создаем подграфик для обработанного изображения
plt.title('Обработанное изображение')  # заголовок для обработанного изображения
plt.imshow(result_image)  # отображаем обработанное изображение
plt.axis('off')  # выключаем оси

plt.show()  # показываем все графики
